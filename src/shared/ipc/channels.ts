/** Envelope used for every invoke response so errors cross IPC intact. */
export type IpcResult<T> = { ok: true; data: T } | { ok: false; error: IpcError }

export interface IpcError {
  code:
    | 'VALIDATION'
    | 'FORBIDDEN'
    | 'NOT_IMPLEMENTED'
    | 'NOT_FOUND'
    | 'CONFLICT'
    | 'UNAVAILABLE'
    | 'DATABASE'
    | 'INTEGRATION'
    | 'INTERNAL'
  message: string
}
