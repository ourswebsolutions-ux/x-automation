/**
 * What each IPC channel requires, enforced in the main process.
 *  - open:     nothing; the lock screen itself needs these.
 *  - unlocked: the PIN. Viewing data, settings, backups and the subscription page.
 *  - premium:  the PIN and an active subscription. Creating, generating and anything acting on X.
 *
 * Exhaustive on purpose: a new channel doesn't compile until someone decides its level here.
 */
